import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { cn } from "@/lib/utils"

import { Icons } from "@/components/icons/icons"

import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex size-full flex-col overflow-hidden text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  commandProps,
  ...props
}: Omit<React.ComponentProps<typeof Dialog>, "children"> & {
  title?: string
  description?: string
  commandProps?: React.ComponentProps<typeof Command>
  children: React.ReactNode
}) {
  return (
    <Dialog {...props}>
      <DialogContent
        data-slot="command-dialog-content"
        className="rounded-2xl bg-popover p-0 shadow-2xl outline-none max-sm:top-16 max-sm:translate-y-0 sm:max-w-lg"
        showCloseButton={false}
        showOverlay={false}
      >
        <DialogHeader className="sr-only">
          <DialogTitle render={<span />}>{title}</DialogTitle>
          <DialogDescription>{description}</DialogDescription>
        </DialogHeader>
        <Command
          {...commandProps}
          className={cn(
            "px-1 outline-none",
            "**:data-[slot=command-input-wrapper]:h-12 [&_[cmdk-input-wrapper]_svg]:size-4 **:[[cmdk-input]]:h-10",
            "**:[[cmdk-group]]:px-1",
            "**:[[cmdk-group-heading]]:px-2 **:[[cmdk-group-heading]]:font-medium **:[[cmdk-group-heading]]:text-muted-foreground",
            "[&_[cmdk-item]_svg]:size-4 **:[[cmdk-item]]:p-2",
            commandProps?.className
          )}
        >
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

