import { renderMermaidSVG } from 'beautiful-mermaid'
import { CodeBlock, Pre } from 'fumadocs-ui/components/codeblock'

// The renderer @imports its fonts from Google; the site's own fonts are
// already loaded, so drop the extra third-party request
const FONT_IMPORT = /@import url\([^)]*\);/g

export function Mermaid({ chart }: { chart: string }) {
  try {
    const svg = renderMermaidSVG(chart.replaceAll('\\n', '\n'), {
      bg: 'var(--color-fd-background)',
      fg: 'var(--color-fd-foreground)',
      interactive: true,
      transparent: true,
    }).replace(FONT_IMPORT, '')

    return (
      <section
        aria-label='Diagram'
        className='overflow-x-auto [&_svg_.mono]:font-mono [&_svg_text]:font-sans'
        // biome-ignore lint/security/noDangerouslySetInnerHtml: SVG is generated by the trusted beautiful-mermaid library
        dangerouslySetInnerHTML={{ __html: svg }}
        // biome-ignore lint/a11y/noNoninteractiveTabindex: wide charts scroll, so keyboard users need to reach the region
        tabIndex={0}
      />
    )
  } catch {
    return (
      <CodeBlock title='Mermaid'>
        <Pre>{chart}</Pre>
      </CodeBlock>
    )
  }
}
